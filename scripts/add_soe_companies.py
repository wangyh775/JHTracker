def normalize_name(name):
    # Remove parenthetical parts
    n1 = re.sub(r'（.*?）', '', name)
    n2 = re.sub(r'\(.*?\)', '', n1)
    # Remove common suffixes that might be omitted
    for suffix in ['集团', '股份有限公司', '有限责任公司', '有限公司', '研究所', '研究院', '公司']:
        n2 = n2.replace(suffix, '')
    return n2.strip().lower()


def main():
    if not os.path.exists(DB_PATH):
        print(f"ERROR: Database not found at {DB_PATH}")
        return

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # Get existing company names
    existing_rows = cursor.execute("SELECT name FROM companies").fetchall()
    existing_exact = set(r[0].lower().strip() for r in existing_rows)
    existing_norm = {normalize_name(r[0]): r[0] for r in existing_rows}

    added = 0
    skipped = 0

    for company in COMPANIES:
        name, industry, city, reason, priority, website = company
        
        name_lower = name.lower().strip()
        name_norm = normalize_name(name)

        # Check if already exists
        if name_lower in existing_exact:
            print(f"  SKIP (exact match): {name}")
            skipped += 1
            continue

        if name_norm in existing_norm and len(name_norm) > 2: # Avoid too short matches
            print(f"  SKIP (matched '{existing_norm[name_norm]}'): {name}")
            skipped += 1
            continue
            
        # Also check for partial matches where one is substring of another
        is_substring_match = False
        for ex_norm, ex_full in existing_norm.items():
            if len(ex_norm) > 3 and len(name_norm) > 3:
                if ex_norm in name_norm or name_norm in ex_norm:
                    print(f"  SKIP (substring match with '{ex_full}'): {name}")
                    is_substring_match = True
                    break
        
        if is_substring_match:
            skipped += 1
            continue

        # Insert
        cursor.execute("""
            INSERT INTO companies (name, industry, city, job_type, match_reason, priority, website, source_list, created_at)
            VALUES (?, ?, ?, '控制/嵌入式/自动化', ?, ?, ?, '央国企-军工-院所', ?)
        """, (name, industry, city, reason, priority, website, datetime.now().isoformat()))
        added += 1
        print(f"  ADD: {name} [{priority}] - {city}")

    conn.commit()
    conn.close()

    print(f"\n{'='*60}")
    print(f"Summary: {added} companies added, {skipped} skipped (already in DB)")
    print(f"Total SOE/defense entries now: {added + len(existing_rows)}")
    print(f"{'='*60}")


if __name__ == "__main__":
    main()