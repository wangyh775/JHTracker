def main():
    conn = sqlite3.connect(DB)
    c = conn.cursor()
    
    # 获取所有公司
    c.execute('SELECT id, name, industry FROM companies')
    rows = c.fetchall()
    
    mapped = 0
    kept = 0
    for rid, name, ind in rows:
        if not ind or ind == '未知':
            continue
        new_ind = INDUSTRY_MAP.get(ind)
        if new_ind:
            c.execute('UPDATE companies SET industry = ? WHERE id = ?', (new_ind, rid))
            mapped += 1
        else:
            kept += 1
            print(f'  未映射: [{ind}] {name}')
    
    conn.commit()
    conn.close()
    print(f'\n✅ 已归并: {mapped} 家')
    print(f'❌ 未匹配(保留原样): {kept} 家')
    
    # 统计归并后分布
    conn2 = sqlite3.connect(DB)
    c2 = conn2.cursor()
    c2.execute('SELECT industry, COUNT(*) FROM companies GROUP BY industry ORDER BY COUNT(*) DESC')
    print('\n归并后行业分布:')
    for row in c2.fetchall():
        print(f'  {row[0]}: {row[1]}')
    conn2.close()

if __name__ == '__main__':
    main()